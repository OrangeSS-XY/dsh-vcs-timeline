/** Simplified Chinese dictionary: base copy plus the redesigned chrome. */
export const zh: Record<string, string> = { ...baseZh, ...uiZh }

/** English dictionary: base copy plus the redesigned chrome. */
export const en: Record<string, string> = { ...baseEn, ...uiEn }

/** All dictionaries by locale. */
export const dictionaries: Record<Locale, Record<string, string>> = { zh, en }

/** Replace `{name}` placeholders in one dictionary template. */
export function interpolate(template: string, params?: Record<string, string | number>): string {
  if (params === undefined) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name]
    return value === undefined ? match : String(value)
  })
}

/** Look one key up in a dictionary, then interpolate its params. */
export function translate(
  locale: Locale,
  key: string,
  params?: Record<string, string | number>,
): string {
  const dictionary = dictionaries[locale] ?? zh
  const template = dictionary[key] ?? key
  return interpolate(template, params)
}

/** Build a translate function bound to one locale. */
export function createTranslator(locale: Locale): TranslateFn {
  return (key: string, params?: Record<string, string | number>): string => translate(locale, key, params)
}

/** Map a raw locale tag (`zh-CN`, `en-US`, ...) to a supported dictionary. */
export function normalizeLocale(raw: string | undefined): Locale {
  return typeof raw === 'string' && raw.toLowerCase().startsWith('en') ? 'en' : 'zh'
}
